import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// The program uses concrete IDL types, so stable Cargo can print the IDL
// fragments without the legacy Anchor CLI's nightly proc-macro flags.
const programPath = resolve('programs/encore');
const result = spawnSync('cargo', ['test', '--locked', '--manifest-path', `${programPath}/Cargo.toml`, '--features', 'idl-build', '__anchor_private_print_idl', '--', '--show-output', '--quiet'], {
  encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'],
  env: { ...process.env, ANCHOR_IDL_BUILD_SKIP_LINT: 'TRUE', ANCHOR_IDL_BUILD_PROGRAM_PATH: programPath, ANCHOR_IDL_BUILD_RESOLUTION: 'TRUE' },
});
if (result.status !== 0) throw new Error('Registry IDL generation failed');
const sections = [...result.stdout.matchAll(/--- IDL begin (\w+) ---\s*([\s\S]*?)\s*--- IDL end \1 ---/g)];
function section(name:string) {
  const match=sections.find((item)=>item[1]===name);
  if(!match)throw new Error(`Missing IDL ${name} fragment`);
  return JSON.parse(match[2]!);
}
const program=section('program');
program.address=String(section('address')).replaceAll('"','');
program.errors=section('errors');
// Keep the client ABI focused on the actual registry instructions and accounts.
const output='packages/solana-client/src/generated';
mkdirSync(output,{recursive:true});
writeFileSync(`${output}/encore.json`,JSON.stringify(program,null,2)+'\n');
writeFileSync(`${output}/program-address.ts`, `// Generated by pnpm chain:generate.\nexport const REGISTRY_ADDRESS = ${JSON.stringify(program.address)};\n`);
console.log(`Generated registry IDL for ${program.address}`);
