import { describe, expect, it } from "vitest";
import { fixtureIssuers, signedFixture } from "./fixture.test-helper";
import { CatalogService, type Release } from "@encore/core";
import type { ProvenanceProof } from "@encore/contracts";
import { mp3Inspector, sha256 } from "../catalog/media";
import { issuerSetHash, verifyContributionProof } from "./schnorr";

const trackId = "d159eab0-e0f6-4717-ad0b-04dd9e0d14fa";
const issuers = fixtureIssuers;
const real = { mode: "real" as const, issuerSetHash: issuerSetHash(issuers), verify: (proof: ProvenanceProof) => verifyContributionProof(proof, issuers) };
const demo = { mode: "simulated" as const, issuerSetHash: null, verify: () => false };

async function draft(originCategory: "HUMAN_CREATED" | "AI_GENERATED", metadata = "") {
  let current: Release;
  const service = new CatalogService({
    create: async (release) => { current = release; },
    get: async () => current,
    mine: async () => [current],
    search: async () => ({ tracks: [], total: 0 }),
    transition: async (_id, _expected, status) => { current = { ...current, status }; },
    append: async (_id, _owner, expected, manifest, manifestHash) => {
      if (current.manifest.version !== expected) throw new Error("Conflict");
      current = { ...current, manifest, manifestHash };
    }
  }, { put: async () => {}, remove: async () => {}, preview: async () => "" }, sha256, mp3Inspector, () => trackId);
  const frame = Buffer.alloc(417);
  frame.set([255, 251, 144, 0]);
  const tag = metadata
    ? Buffer.concat([Buffer.from([73, 68, 51, 3, 0, 0, 0, 0, 0, metadata.length]), Buffer.from(metadata)]) : Buffer.alloc(0);
  const release = await service.upload("artist", {
    title: "Fixture", artistName: "Artist", genre: "Electronic", description: "",
    originCategory, previewConsent: true,
    contributions: [{ mode: "unknown", role: "instrumental", creatorRef: "Artist", consent: true }]
  }, Buffer.concat([tag, frame, frame, frame]));
  return { service, release };
}

function proofFor(service: CatalogService, release: Release): ProvenanceProof {
  return signedFixture(service.proofBinding(release, real.issuerSetHash), sha256.hash({ artifact: "private graph fixture" }));
}

describe("Signed provenance and zero-knowledge possession", () => {
  it("commits exact-audio proof results and makes a retry idempotent", async () => {
    const { service, release } = await draft("AI_GENERATED");
    const proof = proofFor(service, release);
    const input = { expectedVersion: 1, proof };
    const [first, retry] = await Promise.all([
      service.verifyProvenance(trackId, "artist", input, real),
      service.verifyProvenance(trackId, "artist", input, real)
    ]);
    expect(first.manifestHash).toBe(retry.manifestHash);
    expect(first.manifest).toMatchObject({
      version: 2, previousHash: release.manifestHash,
      evidenceStatus: "UNVERIFIED", rightsStatus: "PREVIEW_ALLOWED",
      provenance: { mode: "real", outcome: "role_corroborated", reason: "signed_instrumental" }
    });
    expect(JSON.stringify(first.manifest)).not.toContain(proof.possessionProof);
    expect(JSON.stringify(first.manifest)).not.toContain(proof.credentialKey);
    expect(first.manifestHash).toBe(sha256.hash({ ...first.manifest, audioHash: release.audioHash }));
  });

  it("rejects altered audio, release, graph, and unauthorized signatures", async () => {
    const { service, release } = await draft("AI_GENERATED");
    const proof = proofFor(service, release);
    expect(real.verify(proof)).toBe(true);
    expect(real.verify({ ...proof, graphHash: "1".repeat(64) })).toBe(false);
    expect(real.verify({ ...proof, binding: { ...proof.binding, trackId: "aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa" } })).toBe(false);
    expect(real.verify({ ...proof, contributionSignature: proof.exportSignature })).toBe(false);
    expect(verifyContributionProof(proof, { ...issuers, provider: proof.credentialKey })).toBe(false);
    const mismatched = { ...proof, binding: { ...proof.binding, audioHash: "1".repeat(64) } };
    const result = await service.verifyProvenance(trackId, "artist", { expectedVersion: 1, proof: mismatched }, real);
    expect(result.manifest.provenance?.reason).toBe("binding_mismatch");
  });

  it("keeps a human claim unverified for missing evidence or an AI tag", async () => {
    const clean = await draft("HUMAN_CREATED");
    const result = await clean.service.verifyProvenance(trackId, "artist", { expectedVersion: 1 }, real);
    expect(result.manifest.provenance?.reason).toBe("missing_evidence");
    const marked = await draft("HUMAN_CREATED", "Generated by Suno");
    const flagged = await marked.service.verifyProvenance(trackId, "artist", { expectedVersion: 1 }, real);
    expect(flagged.manifest).toMatchObject({
      originCategory: "HUMAN_CREATED", evidenceStatus: "UNVERIFIED",
      provenance: { outcome: "unverified", reason: "ai_metadata_signal" }
    });
  });

  it("labels simulated outcomes and refuses fixtures in real mode", async () => {
    const { service } = await draft("HUMAN_CREATED");
    const input = { expectedVersion: 1, demoScenario: "supported" as const };
    await expect(service.verifyProvenance(trackId, "artist", input, real)).rejects.toThrow("verification mode");
    const result = await service.verifyProvenance(trackId, "artist", input, demo);
    expect(result.manifest.evidenceStatus).toBe("UNVERIFIED");
    expect(result.manifest.provenance).toMatchObject({ mode: "simulated", outcome: "simulated_supported" });
  });
});
